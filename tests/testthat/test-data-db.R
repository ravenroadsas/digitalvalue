test_that("sync_status derives statuses after each appraisal step", {
  cfg <- test_cfg()
  con <- test_con()
  id <- reg(con, cfg, effort = "L", cost = 3)
  expect_equal(sync_status(con, cfg), id)
  expect_equal(db_get_initiatives(con, id)$status, "4M valuation")
  db_add_m4_line(con, id, m4_calculate("m_direct", list(mm_usd = 1), cfg))
  sync_status(con, cfg)
  expect_equal(db_get_initiatives(con, id)$status, "Expert review")
  db_add_review(con, id, "Approve", list(M = 1), 1, 3)
  sync_status(con, cfg)
  expect_equal(db_get_initiatives(con, id)$status, "Ready")
  expect_length(sync_status(con, cfg), 0)
})

