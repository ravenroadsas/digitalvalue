test_that("4M lines, expert reviews with 4M figures and audits with adoption", {
  cfg <- test_cfg()
  con <- test_con()
  id <- reg(con, cfg)
  db_save_rice(con, id, rice_assess(1000, "L", "High", "M", cfg))
  expect_equal(nrow(db_get_rice(con)), 1)

  lid <- db_add_m4_line(con, id, m4_calculate("p_jobs_success", list(), cfg), "workovers")
  l <- db_get_m4_lines(con, id)
  expect_equal(jsonlite::fromJSON(l$params_json)$n_jobs, 10)
  expect_equal(l$comment, "workovers")

  v <- list(P = 25, R = 0.1, category = "1P", M = 0.2, T = 3)
  db_add_review(con, id, "Approve", v, m4_value(v, cfg)$total, 0.6, "ok", "boss")
  expect_error(db_add_review(con, id, "Maybe"))
  r <- db_get_reviews(con, id)
  expect_equal(r$p_bopd, 25)
  expect_equal(r$r_category, "1P")
  expect_equal(r$value_mm_usd, m4_value(v, cfg)$total)

  a <- list(P = 20, R = 0, M = 0.1, T = 2, category = "2P")
  db_add_audit(con, id, a, 75, 0.5, 1, "fine", "boss")
  au <- db_get_audits(con, id)
  expect_equal(au$adoption_pct, 75)
  expect_equal(au$realization_pct, 50)

  pf <- db_portfolio(con)
  expect_equal(pf$plan_p, 30)
  expect_equal(pf$plan_lines, 1)
  expect_equal(pf$review_decision, "Approve")
  expect_equal(pf$review_p, 25)
  expect_equal(pf$actual_p, 20)
  expect_equal(pf$adoption_pct, 75)
  expect_equal(pf$audited_value_mm_usd, 0.5)

  db_delete_m4_line(con, lid)
  expect_equal(nrow(db_get_m4_lines(con, id)), 0)
})

