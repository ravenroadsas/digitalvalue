test_that("sync_status: Evaluated only after valuation, validation and review", {
  cfg <- test_cfg()
  con <- test_con()
  id <- reg(con, cfg, effort = "L")
  expect_length(sync_status(con, cfg), 0)
  expect_equal(db_get_initiatives(con, id)$status, "Recorded")
  db_add_m4_line(con, id, m4_calculate("m_direct", list(mm_usd = 1), cfg))
  db_add_m4_line(con, id, m4_calculate("c_direct", list(capex_mm_usd = 3, opex_mm_usd_yr = 0), cfg))
  sync_status(con, cfg)
  expect_equal(db_get_initiatives(con, id)$status, "Recorded")      # not validated yet
  vid <- db_request_validation(con, id, "dval", "u1")
  db_decide_validation(con, vid, "validated", "dval")
  sync_status(con, cfg)
  expect_equal(db_get_initiatives(con, id)$status, "Recorded")      # cost 3 >= 1: review required
  db_add_review(con, id, "Approve", list(M = 1, C = 3))
  expect_equal(sync_status(con, cfg), id)
  expect_equal(db_get_initiatives(con, id)$status, "Evaluated")
  expect_length(sync_status(con, cfg), 0)
})

test_that("validation requests, supersession and decisions", {
  cfg <- test_cfg()
  con <- test_con()
  id <- reg(con, cfg)
  expect_error(db_request_validation(con, id, "", "u1"), "validator")
  v1 <- db_request_validation(con, id, "dval", "u1", "first", Sys.time() - 10)
  v2 <- db_request_validation(con, id, "cplan", "u1", "second")
  v <- db_get_validations(con, id)
  expect_equal(v$status[v$validation_id == v1], "superseded")
  expect_equal(nrow(db_get_validations(con, validator = "cplan")), 1)
  expect_equal(nrow(db_get_validations(con, validator = "dval")), 0)
  expect_error(db_decide_validation(con, v1, "validated", "dval"), "No pending")
  db_decide_validation(con, v2, "changes_requested", "cplan", "fix rates")
  pf <- db_portfolio(con)
  expect_equal(pf$validation_status, "changes_requested")
  expect_equal(pf$validator, "cplan")
})

