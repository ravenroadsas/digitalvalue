test_that("value model versions: publish, activate, roundtrip", {
  cfg <- test_cfg()
  con <- test_con()
  set.seed(2)
  d <- data.frame(log_y = rnorm(12), reach_value = runif(12, 1, 4), log_effort = log(runif(12, .5, 8)))
  fit <- stats::lm(log_y ~ reach_value + log_effort, data = d)
  rec <- model_record(fit, "rice_to_review", "multivariable", 0.8)
  m1 <- db_publish_value_model(con, rec, "first", "boss", Sys.time() - 10)
  m2 <- db_publish_value_model(con, rec, "second", "boss")
  v <- db_get_value_models(con, "rice_to_review")
  expect_equal(nrow(v), 2)
  expect_equal(sum(v$active), 1)
  expect_equal(db_active_value_model(con, "rice_to_review")$model_id, m2)
  db_activate_value_model(con, m1)
  back <- db_active_value_model(con, "rice_to_review")
  expect_equal(back$model_id, m1)
  expect_equal(unname(back$coef), unname(stats::coef(fit)), tolerance = 1e-10)
  expect_equal(unname(back$vcov), unname(stats::vcov(fit)), tolerance = 1e-10)
  expect_null(db_active_value_model(con, "review_to_audit"))
  expect_error(db_activate_value_model(con, "nope"), "Unknown")
})

