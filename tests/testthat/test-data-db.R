test_that("old lifecycle statuses migrate once to the simplified lifecycle", {
  cfg <- test_cfg()
  con <- test_con()
  ids <- vapply(1:4, function(i) reg(con, cfg, paste("X", i)), "")
  db_add_m4_line(con, ids[1], m4_calculate("m_direct", list(mm_usd = 1), cfg))
  old <- c("Prioritized", "Closed", "4M valuation", "Rejected")
  for (i in 1:4) DBI::dbExecute(con, sprintf("UPDATE initiatives SET status = '%s' WHERE id = '%s'", old[i], ids[i]))
  DBI::dbExecute(con, "DELETE FROM schema_migrations")
  db_init(con)
  expect_equal(db_get_initiatives(con)$status, c("Evaluated", "Delivered", "Recorded", "Recorded"))
  expect_equal(db_get_validations(con, ids[1])$status, "validated")   # pre-existing 4MC counts as validated
  # migrations run only once: new 4MC lines are not auto-validated
  db_add_m4_line(con, ids[3], m4_calculate("m_direct", list(mm_usd = 1), cfg))
  db_init(con)
  expect_equal(nrow(db_get_validations(con, ids[3])), 0)
})
